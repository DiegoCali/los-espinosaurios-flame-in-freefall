import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const root=new URL('../',import.meta.url);
const read=path=>JSON.parse(readFileSync(new URL(path,root),'utf8'));
const source=readFileSync(new URL('src/entities/saffire/model.ts',root),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const exports={};new Function('exports',compiled)(exports);
const {evaluateSaffire}=exports;
const data=read('src/entities/saffire/evidence.json');
const original=read('../investigations/SAFFIRE/analysis-saffire.json');
assert.deepEqual(data.model.coefficients,original.predictive_model.coefficients);
const fixtures=read('src/entities/saffire/formula-fixtures.json');
for(const f of fixtures)assert.ok(Math.abs(evaluateSaffire(data.model,f.material==='Silicone'?'silicone':'other',f.flow)-f.expected)<1e-12);
for(const flow of [NaN,Infinity,0,19,25])assert.throws(()=>evaluateSaffire(data.model,'other',flow),RangeError);
assert.throws(()=>evaluateSaffire(data.model,'invalid',20),RangeError);
assert.ok(evaluateSaffire(data.model,'silicone',20)<0);
assert.equal(evaluateSaffire(data.model,'silicone',20),evaluateSaffire(data.model,'silicone',24.9));
assert.equal(data.rows.length,9);
assert.ok(data.rows.some(r=>r.actual<0));
console.log(`${fixtures.length} Python/TypeScript formula cases match at 1e-12; domain validation, negative values and silicone invariance pass.`);
