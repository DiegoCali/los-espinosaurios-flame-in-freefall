"""Assemble reports/REPORT.md from processed results, validation and figure captions.

Run after `bass2 aggregate`:  .venv/Scripts/python -m bass2.report
Every number in the report is read from files produced by the pipeline (no hand-typed results).
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from .config import PROJECT_ROOT

REPORTS = PROJECT_ROOT / "reports"
FIGS = REPORTS / "figures"

DISCLOSURE = (
    "Published spread rates were **not** used for the spatial calibration (duct ruler). They **were** used, on the "
    "development tests B1, B2, B3, B4, B5, B7, B12 and M1, to choose the segmentation method (scripts/compare_segmenters.py) "
    "and the regime-segmentation settings (knowledge/methods/spatial_calibration.md §6). Accuracy on those tests is "
    "therefore in-sample. The hold-out slab tests (configs/holdout_tests.yaml) were processed only after every setting "
    "was frozen. The physics QC (configs/qc.yaml, reports/physics_review.md) was done with published values visible, "
    "so QC-filtered statistics are not independent; unfiltered statistics are always reported next to them.")


def _cap(path: Path) -> str:
    md = path.with_suffix(".md")
    return md.read_text(encoding="utf-8").strip() if md.exists() else ""


def _fig(rel: str) -> str:
    p = FIGS / rel
    if not p.exists():
        return ""
    return f"![{p.stem}](figures/{rel})\n\n{_cap(p)}\n"


def _pct(x) -> str:
    return "—" if x is None or not np.isfinite(x) else f"{100 * x:.1f} %"


def _stat_line(name: str, d: dict) -> str:
    if not d:
        return f"| {name} | 0 | — | — | — | — |"
    return (f"| {name} | {d['n']} | {_pct(d['median_abs_rel_error'])} | {100 * d['mean_rel_bias']:+.1f} % | "
            f"{_pct(d['coverage_2sigma'])} | {d.get('spearman_rho', float('nan')):.2f} |")


def build(example_tests: tuple[str, ...] = ("B1", "B4", "M1")) -> Path:
    ens = FIGS / "_ensemble"
    val = json.loads((REPORTS / "validation_summary.json").read_text()) if (REPORTS / "validation_summary.json").exists() else {}
    vt = pd.read_csv(REPORTS / "validation_published.csv") if (REPORTS / "validation_published.csv").exists() else pd.DataFrame()
    rates = pd.read_csv(ens / "steady_rates.csv") if (ens / "steady_rates.csv").exists() else pd.DataFrame()
    fsum = pd.read_csv(ens / "forecast_summary.csv") if (ens / "forecast_summary.csv").exists() else pd.DataFrame()
    tl, tle = val.get("thickness_law", {}), val.get("thickness_law_extended_trusted", {})
    cal = pd.read_csv(PROJECT_ROOT / "data/catalog/spatial_calibration.csv")
    cal_scale, cal_n = float(cal.global_mm_per_px.iloc[0]), int(cal.global_n.iloc[0])
    cal_cv = 100 * float(cal.global_std.iloc[0]) / cal_scale
    sets = val.get("by_set", {})
    qc_counts = rates.qc.value_counts().to_dict() if "qc" in rates else {}

    L = ["# BASS-II flame spread: detection, measurement and forecasting", "",
         "_Generated by `python -m bass2.report` from pipeline outputs. NASA PSI-25 (DOI 10.60555/4qc4-de67, CC0)._", "",
         "## 1. Question",
         "Can flame spread in the ISS BASS-II videos be detected and measured automatically, accurately enough to "
         "reproduce published spread rates, and can the measured time series be forecast?", "",
         "## 2. Data",
         f"- {len(rates)} tests processed (main side-view camcorder video, 720×480 @ 29.97 fps, SAR 10:11): thin PMMA "
         "films (B), thick slabs (M), rods (O, P), SIBAL fabric and spheres (T), Nomex and candle (F).",
         "- Test conditions from the cleaned experimental table, cross-checked against the NASA as-run matrices.",
         "- Telemetry (AIR velocity, FAN voltage, RAD radiometer, clock) read by OCR from the burned-in OSD.",
         "- Data defects: the B14, B18 and B20 main MP4 files are truncated on the NASA server (no `moov` atom) and were "
         "replaced by their original MPEG-TS recordings; M3 has only a rack-camera video recorded during loss of signal.", "",
         "## 3. Method (summary)",
         "1. Frames masked (OSD band, illuminated frames, static artefacts such as LEDs and hot pixels). The flame is "
         "segmented by hysteresis thresholds relative to each frame's background noise (median + k·MAD) on max(RGB), "
         "OR-ed with a blue-excess channel so faint blue leading edges are kept.",
         "2. Sub-pixel leading/trailing edges from the intensity-weighted profile along the spread axis; isolated edge "
         "outliers removed with a Hampel filter.",
         f"3. Spatial calibration from the duct's ruler in illuminated frames (1 cm marks): fixed-FOV camera scale "
         f"{cal_scale:.4f} mm/px ({cal_cv:.1f} % spread between {cal_n} rulers, 2 % allowance for depth).",
         "4. The leading edge is median-binned and split into linear regimes by optimal segmentation; steady V_f = "
         "Theil-Sen slope of the **longest** regime that advances significantly and by ≥ 2 mm, with a 95 % CI widened "
         "for residual autocorrelation. Tests that step the flow also get one rate per FAN plateau.",
         "5. Forecasting models evaluated by rolling-origin backtests (horizons 1–10 s) with MASE, CRPS and 90 % "
         "interval coverage; an autonomous research loop improves the forecaster and segmenter against a fixed harness.",
         "6. External validation against published values (see the disclosure below).", "",
         "## 4. Validation against published spread rates", "",
         f"> {DISCLOSURE}", "",
         "| Set | n | Median abs. error | Mean bias | Within 2σ | Spearman ρ |", "|---|---|---|---|---|---|"]
    d = sets.get("development", {})
    L.append(_stat_line("Development (in-sample), all", d.get("all", {})))
    L.append(_stat_line("Development (in-sample), QC-passed", d.get("qc_passed", {})))
    L.append(_stat_line("Hold-out (frozen settings; not reviewed by the physics QC)", sets.get("holdout", {}).get("all", {})))
    L.append("")
    ha = val.get("holdout_accounting", {})
    if ha:
        L += [f"Hold-out accounting: {ha['n_tests']} tests processed; {ha['n_with_comparison']} produced at least one "
              f"comparison with a published rate; no steady spread was detected in: {', '.join(ha['no_steady_spread']) or 'none'}"
              f"{'; no published step could be matched for: ' + ', '.join(ha['no_matched_step']) if ha['no_matched_step'] else ''}.", ""]
    h = sets.get("holdout", {})
    if h.get("first_or_single_step") or h.get("later_steps"):
        f1, f2 = h.get("first_or_single_step", {}), h.get("later_steps", {})
        L += [f"**Hold-out breakdown.** First or single flow step: n = {f1.get('n', 0)}, median error "
              f"{_pct(f1.get('median_abs_rel_error'))}, bias {100 * f1.get('mean_rel_bias', float('nan')):+.1f} %. "
              f"Later flow steps: n = {f2.get('n', 0)}, median error {_pct(f2.get('median_abs_rel_error'))}, bias "
              f"{100 * f2.get('mean_rel_bias', float('nan')):+.1f} %. After a flow change a thick slab takes minutes to "
              "re-equilibrate, and the per-FAN-plateau window does not wait for that transient, so later-step rates stay "
              "close to the previous step's rate (e.g. M2 step 2). Rates of later flow steps on thick fuels are therefore "
              "not reliable yet; the first/single-step rates are.", ""]
    sm = val.get("step_matching", [])
    if sm:
        avail = sum(x["steps_available"] for x in sm)
        match = sum(x["steps_matched"] for x in sm)
        L += [f"Multi-step slab tests: {match} of {avail} published flow steps could be matched one-to-one (Hungarian "
              "assignment on lag-corrected air velocity) to a measured FAN plateau with a valid rate.", ""]
    if tl.get("slope") is not None:
        L += [f"- **Scale-free thickness law, GMT day 50 films** (n = {tl['n']}, same session as the SDSU values): slope "
              f"**{tl['slope']:.2f} ± {tl['slope_se']:.2f}** (R² {tl['r2']:.2f}); published values give "
              f"{tl.get('published_slope', float('nan')):.2f} ± {tl.get('published_slope_se', float('nan')):.2f}; de Ris theory −1."]
    if tle.get("slope") is not None:
        L += [f"- **Thickness law, all QC-trusted films with O₂ > 19.5 %** (n = {tle['n']}, includes B6, B9, B11, B13, which "
              f"have no published value and were never used for tuning): slope **{tle['slope']:.2f} ± {tle['slope_se']:.2f}** "
              f"(R² {tle['r2']:.2f}). This check is independent of the spatial calibration."]
    L.append("")
    if len(vt):
        L += ["| Comparison | Set | QC | Measured V_f (mm/s) | 95 % CI | Published (mm/s) | Rel. error |",
              "|---|---|---|---|---|---|---|"]
        for r in vt.sort_values(["set", "test_id"]).itertuples():
            L.append(f"| {r.test_id} | {r.set} | {r.qc_status} | {r.vf_measured_mm_s:.4g} | "
                     f"[{r.vf_lo:.3g}, {r.vf_hi:.3g}] | {r.vf_published_mm_s:.4g} | {100 * r.rel_error:+.1f} % |")
        L.append("")
    L += [_fig("_ensemble/G6_parity_published.png"), _fig("_ensemble/G19_thickness_law.png"),
          _fig("_ensemble/G15_threshold_sensitivity.png")]
    if qc_counts:
        L += ["## 5. Physics quality control",
              "Every test was reviewed for physical plausibility (reports/physics_review.md); verdicts are versioned in "
              "configs/qc.yaml and used to select tests for ensemble figures and trends. Counts: " +
              ", ".join(f"{k} {v}" for k, v in sorted(qc_counts.items())) + ". Excluded tests include missed dim burns, "
              "igniter-flash or ignition-growth regimes, rods where the video measures flame-length settling rather than "
              "spread, and insufficient footage. The review saw published values, so it is not an independent test.", ""]
    L += ["## 6. Example tests"]
    for t in example_tests:
        if (FIGS / t).exists():
            L += [f"### {t}", _fig(f"{t}/G1_overlay.png"), _fig(f"{t}/G2_kymograph.png"), _fig(f"{t}/G3_edge_fit.png"),
                  _fig(f"{t}/G4_rate.png"), _fig(f"{t}/G7_size.png"), _fig(f"{t}/G18_telemetry.png")]
    L += ["## 7. Ensemble results", _fig("_ensemble/G13_conditions.png"), _fig("_ensemble/G5_spread_vs_flow.png")]
    L += ["## 8. Forecasting"]
    if len(fsum):
        f = fsum[fsum.target.str.startswith("leading_edge")] if "target" in fsum else fsum
        piv = f.pivot_table(index="model", columns="horizon_s", values="MASE")
        cov = f.groupby("model").coverage.mean()
        L += ["Leading-edge position of the QC-trusted tests, steady windows: mean MASE by horizon (lower is better; < 1 "
              "beats the in-sample naive one-step forecast) and mean 90 % interval coverage. The steady window is chosen "
              "with hindsight and the MASE scale uses the whole series, so these numbers describe forecasting *within* a "
              "steady-spread regime.", "",
              "| Model | " + " | ".join(f"h={h:g} s" for h in piv.columns) + " | coverage |",
              "|---|" + "---|" * (len(piv.columns) + 1)]
        for m, row in piv.iterrows():
            L.append(f"| {m} | " + " | ".join(f"{v:.2f}" for v in row.values) + f" | {cov[m]:.2f} |")
        L.append("")
    L.append(_fig(f"{example_tests[0]}/G9_forecast.png"))
    L += [_fig("_ensemble/G11_skill.png"), _fig("_ensemble/G10_residuals.png"), _fig("_ensemble/G12_calibration.png"),
          _fig("_ensemble/G16_loop_progress.png")]
    res = PROJECT_ROOT / "research/results.tsv"
    if res.exists():
        r = pd.read_csv(res, sep="\t")
        r = r[np.isfinite(r.val_score)]
        kept = r[r.status == "keep"]
        if len(kept):
            best = kept.loc[kept.val_score.idxmin()]
            L += [f"Autonomous research loop: {len(r)} evaluations; best val_score **{best.val_score:.3f}** versus "
                  f"{r.val_score.iloc[0]:.3f} for the v0 baseline (lower is better). Best change: {best.description}. "
                  "The loop's spread-rate component uses the development tests, so loop gains on R are in-sample too.", ""]
    L += ["## 9. Limitations",
          "- The ruler graduation (1 cm major marks) is inferred from duct geometry; NASA documents do not state it.",
          "- Development accuracy is in-sample (see §4); the hold-out slab results are the out-of-sample evidence.",
          f"- Thick slabs: later flow steps are over-estimated (hold-out median error "
          f"{_pct(sets.get('holdout', {}).get('later_steps', {}).get('median_abs_rel_error'))}) because the per-step window "
          "starts before the spread re-equilibrates after the flow change; a transient-aware window is the next fix.",
          "- Faint flames can depend on the segmentation threshold (G15 lists which tests are robust and which are not); "
          "this systematic uncertainty is not included in the per-test CIs.",
          "- Segmentation is scored on synthetic flames until a hand-labelled gold set exists.",
          "- OSD OCR occasionally misses the last RAD digit (left as NaN, never guessed).", "",
          "## 10. Reproduce (from investigations/BASS-II, Windows venv)", "```bash",
          ".venv/Scripts/python scripts/download_study.py && .venv/Scripts/python scripts/download_study.py holdout_tests.yaml",
          ".venv/Scripts/python scripts/calibrate_study.py",
          ".venv/Scripts/python scripts/analyze_study.py --workers 5      # videos -> frames, regimes, figures",
          ".venv/Scripts/python scripts/refit_study.py                    # regimes/backtests/figures from saved frames",
          ".venv/Scripts/python scripts/compare_segmenters.py             # development-only segmenter comparison",
          ".venv/Scripts/python scripts/sensitivity.py",
          ".venv/Scripts/bass2 aggregate && .venv/Scripts/python -m bass2.report && .venv/Scripts/python scripts/build_site.py",
          "```", ""]
    out = REPORTS / "REPORT.md"
    out.write_text("\n".join(x for x in L if x is not None), encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build())
